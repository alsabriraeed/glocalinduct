"""Canonical hashing and ID generation. No LLM ever computes these (guide §4, §5)."""
from __future__ import annotations

import hashlib
import json
import math
import secrets
import unicodedata
from datetime import datetime, timezone
from typing import Any


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def _canonical(obj: Any) -> Any:
    """Return a JSON-serialisable structure with NFC strings and no NaN/Inf."""
    if isinstance(obj, str):
        return unicodedata.normalize('NFC', obj)
    if isinstance(obj, float):
        if math.isnan(obj) or math.isinf(obj):
            raise ValueError('NaN/Inf cannot be hashed canonically')
        return obj
    if isinstance(obj, dict):
        return {_canonical(k): _canonical(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_canonical(v) for v in obj]
    return obj


def canonical_json(obj: Any) -> str:
    """Sorted keys, fixed separators, NFC strings, no NaN (guide §5)."""
    return json.dumps(_canonical(obj), sort_keys=True, separators=(',', ':'), ensure_ascii=False)


def payload_hash(obj: Any) -> str:
    return sha256_text(canonical_json(obj))


def new_id(prefix: str) -> str:
    """Opaque persistent ID generated by code."""
    return f'{prefix}_{secrets.token_hex(8)}'


def deterministic_id(prefix: str, *parts: str) -> str:
    body = '\x1f'.join(parts)
    return f'{prefix}_{sha256_text(body)[:24]}'


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.%fZ')
